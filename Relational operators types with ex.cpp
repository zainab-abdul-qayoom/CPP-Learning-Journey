#include<iostream>
using namespace std;
int main()
{
	/*    True (1)   and False (0)
	Relational /comparison operators:
		relation b/w two values
		Six types of relational operators are:
			1. Equal to ==     ex: a == b
			2. Not Equal to !=  ex: a != b
			3. Greater than >    ex: a > b
			4. Less than   <      ex: a < b
			5. Greater than or equal to >=   ex: a >= b
			6. Less than or equal to <=       ex: a <= b */
			
			
	 int a = 10;
	 int b = 20;
	 cout<<"\n \t Relational operator";
	 cout<<"\n \t" << (a==b)<<endl;   //0
	 cout<<"\n \t" << (a!=b)<<endl;   //1
	 cout<<"\n \t" << (a>b)<<endl;    //0
	 cout<<"\n \t" << (a<b)<<endl;   //1
	 cout<<"\n \t" << (a<=b)<<endl;  //1
	 cout<<"\n \t" << (a>=b)<<endl; //0
		
}
