#include<iostream>
using namespace std;
int main()
{
	//escape sequences only used with  cout statement. 
	cout<<"\a"; //a means alert or alarm
	cout<<"\b"; //b means backspace
	cout<<"\t"; //t means horizontal tab
	cout<<"\n"; //n means new line or line feed
	cout<<"\r"; //r means carriage return
	cout<<"\\"; //"\\" backslash 
	cout<<"\'"; //  single quotation print
	cout<<"\""; //   double quotation print
}

