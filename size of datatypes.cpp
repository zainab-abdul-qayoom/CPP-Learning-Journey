#include<iostream>
using namespace std;
int main()
{
	int a = 10;
	cout<<"Size of int: "<<sizeof(a)<<endl;
	
	float b = 10;
	cout<<"Size of float: "<<sizeof(b)<<endl;
	
	double c = 10;
	cout<<"Size of double: "<<sizeof(c)<<endl;
	
	char d = 10;
	cout<<"Size of char: "<<sizeof(d)<<endl;
}
