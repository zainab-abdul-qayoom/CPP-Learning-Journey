#include<iostream>
using namespace std;
int main()
{
	float radius=5.0;
	float diameter=(2*radius);
	float circumference (2*3.14*radius);
	float area(3.14*radius*radius);
	cout<<"Diameter: "<<diameter<<endl;
	cout<<"Circumference: "<<circumference<<endl;
	cout<<"Area: "<<area<<endl;
	
	
	
}
