#include<iostream>
using namespace std;
int main(){
	//Relation operater: 
	// == : equal to
	//!= : not equal to
	//< : less than
	//> : Greater than
	//<= : less than equal to
	//>= : Greater than equal to
	// result : true = 1 , false = 0
	
	int a = 5;
	int b = 6;
	int c;
	c = a >= b;		// 5 >= 6 ===>
	c = a >= 9;
	cout<<c;
}
